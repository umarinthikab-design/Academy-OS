import assert from "node:assert/strict";
import { sanitizePhotoUrl } from "../lib/photo";
import { safeSquadReturn } from "../lib/squadReturn";
assert.equal(sanitizePhotoUrl("data:image/jpeg;base64,/9j/2Q=="), "data:image/jpeg;base64,/9j/2Q==");
assert.equal(sanitizePhotoUrl("data:image/png;base64,aGVsbG8="), "data:image/png;base64,aGVsbG8=");
assert.equal(sanitizePhotoUrl("data:image/svg+xml;base64,aGVsbG8="), null);
assert.equal(sanitizePhotoUrl("data:image/jpeg;base64," + "A".repeat(256 * 1024)), null);
assert.equal(sanitizePhotoUrl("data:image/jpeg;base64,<script>"), null);
assert.equal(sanitizePhotoUrl("javascript:alert(1)"), null);
assert.equal(sanitizePhotoUrl("https://photos.example.invalid/avatar.jpg"), "https://photos.example.invalid/avatar.jpg");
assert.equal(sanitizePhotoUrl(""), null);
assert.equal(safeSquadReturn("/squad?status=ACTIVE#player-card-123"), "/squad?status=ACTIVE#player-card-123");
assert.equal(safeSquadReturn("https://evil.example.invalid"), "/squad");
assert.equal(safeSquadReturn("//evil.example.invalid/squad"), "/squad");
assert.equal(safeSquadReturn("/squad/../settings"), "/squad");
assert.equal(safeSquadReturn("/squad/123"), "/squad");
assert.equal(safeSquadReturn("/squad\\evil"), "/squad");
assert.equal(safeSquadReturn(null), "/squad");
console.log("15 assertions passed: bounded raster photo payloads and local squad return URLs.");
